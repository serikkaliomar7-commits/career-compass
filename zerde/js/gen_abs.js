/* Зерде — генератор темы «Модуль және координаталық түзу» (m_abs).
 * Уровень 4 регистрируем в Z.gen4. */
(function (root) {
  'use strict';
  var Z = root.Z;
  var U = Z.util, fmt = U.fmt;
  var G = Z.gen, G4 = Z.gen4 = Z.gen4 || {};
  var H = Z.genHelpers, Q = H.Q, expr = H.expr;

  /* ---------- Модуль және координаталық түзу ---------- */
  function minus(x) { return x < 0 ? '+ ' + (-x) : '− ' + x; }   // «x − a» при a < 0 → «x + |a|»
  function num(x) { return x < 0 ? '−' + (-x) : String(x); }
  G.m_abs = function (r, lvl) {
    if (lvl === 1) {
      var a = r.int(3, 15), b = r.int(2, 12), k = r.int(0, 2);
      var s = k === 0 ? '|−' + a + '| − |' + b + '|' : k === 1 ? '|' + b + ' − ' + a + '|' : '−|−' + a + '| + |−' + b + '|';
      var v = k === 0 ? a - b : k === 1 ? Math.abs(b - a) : b - a;
      return Q('Өрнектің мәнін табыңыз:' + expr(s), 'Найдите значение выражения:' + expr(s), v, [-v, a + b, -(a + b)],
        'Модуль — нөлге дейінгі қашықтық, ол теріс болмайды: ' + s + ' = ' + fmt(v) + '.', 'Модуль — расстояние до нуля, он неотрицателен: ' + s + ' = ' + fmt(v) + '.');
    }
    if (lvl === 2) {
      if (r.chance(0.5)) {   // екі бөлшек сан арасындағы бүтін сандардың қосындысы
        var lo = Math.round((-r.int(3, 9) - r.pick([0.3, 0.5, 0.8])) * 10) / 10, hi = Math.round((r.int(2, 8) + r.pick([0.2, 0.4, 0.7])) * 10) / 10, sum = 0;
        for (var i = Math.ceil(lo); i <= Math.floor(hi); i++) sum += i;
        return Q(fmt(lo) + ' мен ' + fmt(hi) + ' сандарының арасында орналасқан барлық бүтін сандардың қосындысын табыңыз.', 'Найдите сумму всех целых чисел, расположенных между ' + fmt(lo) + ' и ' + fmt(hi) + '.',
          sum, [sum + 1, -sum, sum - Math.floor(hi)], 'Қарама-қарсы сандар жұбы жойылады: ' + Math.ceil(lo) + ' … ' + Math.floor(hi) + ' қосындысы ' + sum + '.',
          'Противоположные числа взаимно уничтожаются: сумма ' + Math.ceil(lo) + ' … ' + Math.floor(hi) + ' равна ' + sum + '.');
      }
      var p = r.int(5, 20), q = p + r.int(10, 30);
      return Q(p + ' < x < ' + q + ' екені белгілі. |x − ' + p + '| + |x − ' + q + '| өрнегінің мәні неге тең?', 'Известно, что ' + p + ' < x < ' + q + '. Чему равно |x − ' + p + '| + |x − ' + q + '|?',
        q - p, [p + q, -(p + q), p - q], 'x − ' + p + ' > 0, ал x − ' + q + ' < 0: (x − ' + p + ') + (' + q + ' − x) = ' + (q - p) + '.', 'x − ' + p + ' > 0, x − ' + q + ' < 0: (x − ' + p + ') + (' + q + ' − x) = ' + (q - p) + '.');
    }
    if (r.chance(0.5)) {   // lvl 3: координаталық түзудегі нүктелер (образец №3)
      var A = r.int(-10, 5), B = A + r.pick([8, 12, 16, 20]), k1 = r.pick([2, 4]), k2 = 2, BC = (B - A) / k1, CD = BC / k2;
      if (CD % 1) { BC = (B - A) / 2; CD = BC / 2; k1 = 2; }
      var D = B + BC + CD;
      return Q('Координаталық түзуде A, B, C, D нүктелері осы ретпен орналасқан. A(' + num(A) + '), B(' + num(B) + '). AB = ' + k1 + ' · BC, BC = ' + k2 + ' · CD. D нүктесінің координатасын табыңыз.',
        'Точки A, B, C, D расположены на координатной прямой последовательно. A(' + num(A) + '), B(' + num(B) + '). AB = ' + k1 + ' · BC, BC = ' + k2 + ' · CD. Найдите координату точки D.',
        D, [B + BC, D + CD, B - A + BC + CD], 'AB = ' + (B - A) + ', BC = ' + BC + ', CD = ' + CD + '. D = ' + B + ' + ' + BC + ' + ' + CD + ' = ' + D + '.', 'AB = ' + (B - A) + ', BC = ' + BC + ', CD = ' + CD + '. D = ' + D + '.');
    }
    var n = r.int(3, 9);
    return Q('|x| < ' + n + ' теңсіздігін неше бүтін сан қанағаттандырады?', 'Сколько целых чисел удовлетворяют неравенству |x| < ' + n + '?',
      2 * n - 1, [n - 1, 2 * n, 2 * n + 1], '−' + (n - 1) + ' … ' + (n - 1) + ': ' + (n - 1) + ' теріс, ' + (n - 1) + ' оң және 0. Барлығы ' + (2 * n - 1) + '.', 'От −' + (n - 1) + ' до ' + (n - 1) + ': всего ' + (2 * n - 1) + ' (не забудьте 0).');
  };
  G4.m_abs = function (r) {
    if (r.chance(0.5)) {   // |x − a| = b түбірлерінің қосындысы
      var a = r.int(-9, 9), b = r.int(2, 12);
      if (a === 0) a = 4;
      return Q('|x ' + minus(a) + '| = ' + b + ' теңдеуінің түбірлерінің қосындысын табыңыз.', 'Найдите сумму корней уравнения |x ' + minus(a) + '| = ' + b + '.',
        2 * a, [a + b, 2 * b, 0], 'x = ' + num(a + b) + ' немесе x = ' + num(a - b) + '. Түбірлер ' + num(a) + ' санына қатысты симметриялы, қосындысы ' + num(2 * a) + '.',
        'x = ' + num(a + b) + ' или x = ' + num(a - b) + '. Корни симметричны относительно ' + num(a) + ', сумма ' + num(2 * a) + '.');
    }
    var p = r.int(-8, 2), q = p + r.int(4, 15);
    if (p === 0) p = -3;
    if (q === 0) q = 5;
    return Q('|x ' + minus(p) + '| + |x ' + minus(q) + '| өрнегінің ең кіші мәні неге тең?', 'Чему равно наименьшее значение выражения |x ' + minus(p) + '| + |x ' + minus(q) + '|?',
      q - p, [0, Math.abs(p) + Math.abs(q) === q - p ? q - p + 2 : Math.abs(p) + Math.abs(q), Math.round((q - p) / 2)],
      'Бұл — x нүктесінен ' + num(p) + ' және ' + num(q) + ' нүктелеріне дейінгі қашықтықтардың қосындысы. x осы нүктелердің арасында болса, ол ' + (q - p) + '-ге тең және одан кем болмайды.',
      'Это сумма расстояний от x до точек ' + num(p) + ' и ' + num(q) + '. Если x между ними, сумма равна ' + (q - p) + ' — меньше не бывает.');
  };
})(typeof window !== 'undefined' ? window : globalThis);
